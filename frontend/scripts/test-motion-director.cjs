// Uses an already-installed Playwright and Chromium; never installs packages.
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE)
const baseURL = process.env.MOTION_TEST_URL || 'http://127.0.0.1:13001'
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64')

;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
    const errors = []
    page.on('pageerror', error => errors.push(String(error)))
    await page.goto(`${baseURL}/motion-director`)
    await page.getByRole('heading', { name: /Motion Director/ }).waitFor()
    await page.getByLabel('Upload reference images').setInputFiles({ name: 'phone-reference.png', mimeType: 'image/png', buffer: png })
    const canvas = page.getByRole('img', { name: /Draw arrow/ })
    await canvas.waitFor()
    await page.getByLabel('Marker label').fill('camera right')
    const rect = await canvas.boundingBox()
    await page.mouse.move(rect.x + rect.width * .2, rect.y + rect.height * .3)
    await page.mouse.down()
    await page.mouse.move(rect.x + rect.width * .8, rect.y + rect.height * .6, { steps: 6 })
    await page.mouse.up()
    assert.equal(await page.getByLabel('Director', { exact: true }).inputValue(), 'manual')
    await page.getByRole('button', { name: 'subject', exact: true }).click()
    await page.getByLabel('Marker label').fill('traveler')
    await page.touchscreen.tap(rect.x + rect.width * .5, rect.y + rect.height * .5)
    let saved = JSON.parse(await page.evaluate(() => localStorage.getItem('neonforge-motion-director-v0.1')))
    assert.equal(saved.annotations.length, 2)
    assert.equal(saved.annotations[1].kind, 'subject')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    saved = JSON.parse(await page.evaluate(() => localStorage.getItem('neonforge-motion-director-v0.1')))
    assert.equal(saved.annotations.length, 1)
    await page.getByLabel('Cinematic prompt').fill('Track a traveler through a neon street; preserve their identity.')
    await page.getByRole('button', { name: 'Plan shot', exact: true }).click()
    await page.getByRole('heading', { name: '3. Review & generate' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Generate H3 video', exact: true }).isEnabled(), true)
    await page.getByRole('button', { name: 'Generate H3 video', exact: true }).click()
    await page.getByRole('link', { name: 'Download video', exact: true }).first().waitFor()
    await page.locator('video').first().evaluate(video => new Promise((resolve, reject) => {
      if (video.readyState >= 1) return resolve()
      video.onloadedmetadata = resolve; video.onerror = () => reject(new Error('Video did not decode'))
    }))
    const download = page.waitForEvent('download')
    await page.getByRole('link', { name: 'Download video', exact: true }).first().click()
    assert.match((await download).suggestedFilename(), /\.mp4$/)
    await page.getByLabel('Cinematic prompt').fill('A second take with a smooth pull back and a composed ending.')
    await page.getByRole('button', { name: 'Plan shot', exact: true }).click()
    await page.getByRole('button', { name: 'Generate H3 video', exact: true }).click()
    await page.waitForFunction(() => document.querySelectorAll('a[href*="/download"]').length >= 2)
    const comparisons = page.getByRole('checkbox', { name: 'Compare take' })
    await comparisons.nth(0).check(); await comparisons.nth(1).check()
    await page.getByRole('heading', { name: 'Compare takes', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Play both from start' }).isVisible(), true)
    assert.equal(await page.locator('option[value="grok"]').evaluate(option => option.disabled), true)
    if (!await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)) {
      await page.screenshot({ path: '/tmp/neonforge-motion-phone-overflow.png', fullPage: true })
      console.log(await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth,
        overflow: [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > innerWidth + 1).slice(0, 12).map(el => ({ tag: el.tagName, class: el.className, width: el.getBoundingClientRect().width })) })))
    }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    await page.reload()
    await page.getByRole('heading', { name: /Motion Director/ }).waitFor()
    await page.getByRole('img', { name: /Draw arrow/ }).waitFor()
    assert.match(await page.getByLabel('Cinematic prompt').inputValue(), /second take/)
    saved = JSON.parse(await page.evaluate(() => localStorage.getItem('neonforge-motion-director-v0.1')))
    assert.equal(saved.annotations.length, 1)
    await page.getByRole('button', { name: 'Clear this image', exact: true }).click()
    saved = JSON.parse(await page.evaluate(() => localStorage.getItem('neonforge-motion-director-v0.1')))
    assert.equal(saved.annotations.length, 0)
    await page.getByLabel('Upload reference images').setInputFiles([
      { name: 'second-reference.png', mimeType: 'image/png', buffer: png },
      { name: 'third-reference.png', mimeType: 'image/png', buffer: png },
    ])
    await page.getByRole('button', { name: /Picture 3/ }).waitFor()
    assert.equal(await page.getByLabel('Reference use').inputValue(), 'reference')
    await page.screenshot({ path: '/tmp/neonforge-motion-phone.png', fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('PASS: phone upload, pointer/touch drawing, undo/clear, editable persistence, multi-reference, shot planning, mocked H3, decodable preview, download, comparison, disabled Grok, responsive widths')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
